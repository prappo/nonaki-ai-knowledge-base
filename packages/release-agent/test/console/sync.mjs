#!/usr/bin/env node
/**
 * Copy the WP Simple Pay Release Console's own tests into test/console/,
 * rewriting only their imports so they run against release-agent (through
 * adapter.ts) instead of the console's server modules. Test bodies are never
 * edited: if they pass, the recipe + engine behave like the console.
 *
 *   node test/console/sync.mjs [git-ref]        (default: origin/develop)
 *   WPSP_ROOT=<wp-simple-pay-pro checkout>      (default: the Local site path)
 */

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import path from "node:path";

const WPSP_ROOT =
  process.env.WPSP_ROOT ?? "/Users/prince/Local Sites/wpsp/app/public/wp-content/plugins/wp-simple-pay-pro";
const ref = process.argv[2] ?? "origin/develop";
const here = import.meta.dirname;

/** The console modules these tests cover. */
const FILES = [
  "stages", "version", "health", "risk", "github", "notifications", "config",
  "runner", "phase3-runner", "resume", "store", "transcript",
];
/** Test support files copied alongside (imports rewritten the same way). */
const SUPPORT = ["helpers.ts"];

const git = (...args) => execFileSync("git", ["-C", WPSP_ROOT, ...args], { encoding: "utf8" });
const commit = git("rev-parse", "--short", ref).trim();

for (const name of FILES) {
  const source = `tools/release-console/test/${name}.test.ts`;
  let text = git("show", `${ref}:${source}`);

  // the console's server modules → the adapter
  text = text.replace(/from '\.\.\/server\/[\w/]+\.ts'/g, "from './adapter.ts'");
  // reads of the plugin's own files (.claude/commands) → the WPSP checkout
  const usesRoot = /import\.meta\.dirname, ['`]\.\.\/\.\.\/\.\.\//.test(text);
  text = text.replace(/import\.meta\.dirname, (['`])\.\.\/\.\.\/\.\.\//g, "WPSP_ROOT, $1");

  const header =
    `// Synced from wp-simple-pay-pro ${ref} (${commit}): ${source}\n` +
    `// Generated by test/console/sync.mjs. Only imports were rewritten; do not edit by hand.\n` +
    (usesRoot ? `import { WPSP_ROOT } from './adapter.ts';\n` : "");

  writeFileSync(path.join(here, `${name}.test.ts`), header + text);
  console.log(`✓ ${name}.test.ts  ←  ${ref} (${commit})`);
}

for (const file of SUPPORT) {
  const source = `tools/release-console/test/${file}`;
  const text = git("show", `${ref}:${source}`).replace(/from '\.\.\/server\/[\w/]+\.ts'/g, "from './adapter.ts'");
  writeFileSync(path.join(here, file), `// Synced from wp-simple-pay-pro ${ref} (${commit}): ${source}\n// Generated by test/console/sync.mjs. Only imports were rewritten; do not edit by hand.\n` + text);
  console.log(`✓ ${file}  ←  ${ref} (${commit})`);
}
